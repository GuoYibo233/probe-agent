def step_c1_gen(cfg, state, pr=None):
    """c1_gen: generate the three launch artifacts for the collection batch from the manifest.
    If they already exist, treat it as done -- gen-launch without --force refuses to
    overwrite, so do not force it to run."""
    pr = pr or Probes()
    d = run_dir(cfg)
    have = [n for n in GEN_FILES if (d / n).exists()]
    if len(have) == len(GEN_FILES):
        # Claiming an existing artifact also records its sha1: c2/c5 use it to check "was the
        # artifact generated from the current manifest" (C9). A claimed one can only be recorded on
        # the basis of "the human vouches it matches" -- but once it is recorded, a later manifest
        # change gets caught.
        h = manifest_sha1(cfg)
        if h:
            state["manifest_sha1"] = h
        return advanced("the three generated artifacts already exist", str(d))
    if have:
        miss = [n for n in GEN_FILES if n not in have]
        return blocked("only half the set of generated artifacts exist",
                       f"{d} already has {have}, missing {miss}; gen-launch without --force will"
                       "refuse to overwrite -- manually confirm the origin of the leftover files, delete them, or add --force yourself to regenerate")
    mp = manifest_path(cfg)
    if not mp.exists():
        return blocked("collection manifest does not exist", str(mp))
    rc, _ = pr.run_cmd(PYRUN + ["gen-launch", "--config", str(mp)],
                       cwd=ROOT, log=step_log(cfg, "c1_gen"))
    if rc != 0:
        return blocked("gen-launch exited non-zero",
                       f"rc={rc}; log {step_log(cfg, 'c1_gen')}")
    miss = [n for n in GEN_FILES if not (d / n).exists()]
    if miss:
        return blocked("gen-launch finished but the generated artifacts are incomplete", f"{d} is missing {miss}")
    h = manifest_sha1(cfg)
    if h:
        state["manifest_sha1"] = h
    return advanced("the three generated artifacts have been generated", str(d))


def step_c2_servers(cfg, state, pr=None):
    """c2_servers: G1 dirty-tree check -> G2 live probe for a free card -> launch vLLM (launch_servers.py is idempotent)."""
    pr = pr or Probes()
    bad = gate_manifest_unchanged(cfg, state, "launch collection service")
    if bad:
        return bad
    mf = manifest_of(cfg)
    servers = mf["servers"]
    bad = gate_clean_tree(pr, "launch collection service")
    if bad:
        return bad
    # Session existence must be checked before probing the card: once the service is up it holds
    # the card itself, so probing again will never show FREE; getting the order backwards would
    # leave an already-launched batch permanently stuck on blocked
    down = [s for s in servers if not pr.has_session(s["host"], s["session"])]
    if not down:
        return advanced(f"all {len(servers)} service sessions are up",
                        ", ".join(s["session"] for s in servers))
    busy = []
    for s in down:
        ok, why = pr.probe_free(s["host"], str(s["gpu"]))
        if not ok:
            busy.append(f"{s['host']}:{s['gpu']} {why}")
    if busy:
        return blocked("G2 target card is not FREE",
                       "\n".join(busy) + "\nto change cards, edit servers[].gpu in the manifest "
                       "and the session name, then re-run gen-launch with --force")
    rc, _ = pr.run_cmd([sys.executable, "launch_servers.py"],
                       cwd=run_dir(cfg), log=step_log(cfg, "c2_servers"))
    if rc != 0:
        return blocked("launch_servers.py exited non-zero",
                       f"rc={rc}; log {step_log(cfg, 'c2_servers')}")
    return launched(f"{len(down)} vLLM instances launched",
                    "bringing them all up takes a few minutes, next step c3_health verifies G3")


def step_c3_health(cfg, state, pr=None):
    """c3_health: G3 requires each instance's log to show startup complete and /v1/models to respond.

    When the log does not have that line yet, probe the tmux session once more: session still
    there = the service is warming up, leave the state as is and wait for the next run; session
    not found = this instance came up and then died (vLLM running out of GPU memory and
    crashing on the spot is the most common case), and that log line will never appear, so
    waiting longer is pointless -- block, and lay out the session name and log path for a human
    to read (review C8). has_session also returns False when the ssh probe cannot run, so the
    wording says "could not probe" rather than asserting "crashed".
    """
    pr = pr or Probes()
    bad, dead = [], []
    for s in manifest_of(cfg)["servers"]:
        log = SERVE_LOG_DIR / f"{s['session']}.log"
        if not file_contains(log, HEALTH_MARK):
            if pr.has_session(s["host"], s["session"]):
                bad.append(f"{s['session']}: log does not yet have {HEALTH_MARK!r}"
                           f"(session is still up, treat as warming up and wait); log {log}")
            else:
                dead.append(f"{s['session']}({s['host']}:{s['port']}): "
                            f"tmux session cannot be found, and the log has no {HEALTH_MARK!r};"
                            f"log {log}")
            continue
        ok, why = pr.http_get(f"http://{s['host']}:{s['port']}/v1/models")
        if not ok:
            bad.append(f"{s['host']}:{s['port']}/v1/models did not respond: {why}")
    if dead:
        return blocked("G3 some instance's session cannot be found",
                       "\n".join(dead + bad)
                       + "\nthese instances will not come back on their own: read the tail of the log to find the cause"
                         "(out of GPU memory and port already in use are the most common), after fixing it, under "
                       + str(run_dir(cfg)) + " re-run "
                         "`python3 launch_servers.py` (idempotent, only fills in the ones that did not come up)")
    if bad:
        return waiting("G3 services not all up", "\n".join(bad))
    n = len(manifest_of(cfg)["servers"])
    return advanced(f"G3 {n} instances all green", "log shows startup complete and /v1/models responds")


def step_c4_smoke(cfg, state, pr=None):
    """c4_smoke: collect one task, criterion = K files / last line final / seeds matching position by position."""
    pr = pr or Probes()
    mf = manifest_of(cfg)
    d, k, seeds = smoke_dir(cfg), k_of(cfg), seeds_of(cfg)
    # Check the seed table length first: if this comes after smoke_traj_check, a short seed table
    # would make seeds[i] raise IndexError first, and a human would see a traceback instead of
    # this blocked (review C10)
    if k > 1 and len(seeds) != k:
        return blocked("seed table does not match the trajectory count per task",
                       f"trajs_per_unit={k}, collect.seeds has {len(seeds)}"
                       f": {seeds}; align the two, then re-run")
    ok, why = smoke_traj_check(d, k, seeds, cfg["env"])
    if ok:
        return advanced("G4 smoke criteria already met", str(d))
    s0 = mf["servers"][0]
    preset = mf.get("gptoss_client_preset") or "default"
    cmd = PYRUN + ["collect-aw", "--preset", preset,
                   "--base-url", f"http://{s0['host']}:{s0['port']}/v1",
                   # The endpoint and model name are given explicitly from the manifest's servers[0], overriding
                   # the preset server section -- smoke hits the service this batch actually launched
                   "--model", cfg["model_full"],
                   "--split", "train", "--n", "1", "--max-steps", "30",
                   "--outdir", str(d), "--exp", f"{cfg['collect']['run_id']}smk"]
    if k > 1:
        cmd += ["--traj-per-task", str(k),
                "--seeds", ",".join(str(x) for x in seeds)]
    rc, _ = pr.run_cmd(cmd, cwd=ROOT, log=step_log(cfg, "c4_smoke"))
    if rc != 0:
        return blocked("smoke collection exited non-zero",
                       f"rc={rc}; log {step_log(cfg, 'c4_smoke')}")
    ok, why = smoke_traj_check(d, k, seeds, cfg["env"])
    if not ok:
        return blocked("G4 smoke criteria not met", why)
    return advanced("G4 smoke passed", f"{k} trajectories / seeds {seeds} match one to one")


def step_c5_clients(cfg, state, pr=None):
    """c5_clients: launch client pieces + the three registrations (G16's manual backfill path)."""
    pr = pr or Probes()
    bad = gate_manifest_unchanged(cfg, state, "launch collection client")
    if bad:
        return bad
    mf = manifest_of(cfg)
    bad = gate_clean_tree(pr, "launch collection client")
    if bad:
        return bad
    host = pr.local_host()
    sess = client_sessions(cfg)
    down = [s for s in sess if not pr.has_session(host, s)]
    fired = False
    if down:
        rc, _ = pr.run_cmd(["bash", "launch_clients.sh"], cwd=run_dir(cfg),
                           log=step_log(cfg, "c5_clients"))
        if rc != 0:
            return blocked("launch_clients.sh exited non-zero",
                           f"rc={rc}; log {step_log(cfg, 'c5_clients')}")
        fired = True
    ok, why = register_collect(cfg, pr, host, sess)
    if not ok:
        return blocked("the three registrations were not all completed", why)
    if fired:
        return launched(f"{len(down)} client pieces launched", f"the three registrations have been filled in; {len(sess)} pieces total")
    return advanced("all client pieces are up, registrations are complete", f"{len(sess)} pieces total")


def register_collect(cfg, pr, host, sess):
    """G16's three registrations: the job ledger (one client entry + one entry per service instance),
    record start, and RUNMETA. Already-registered ones are skipped -- a duplicate registration
    is rejected by the CLI on the spot (a guardrail, not an obstacle)."""
    rid = cfg["collect"]["run_id"]
    mf = manifest_of(cfg)
    names = pr.ledger_names()
    log = step_log(cfg, "c5_clients")
    if rid not in names:
        pieces = []
        for s in sess:
            pieces += ["--piece", f"{host}:cpu:{s}:{client_log(cfg, s)}"]
        rc, _ = pr.run_cmd(
            PYRUN + ["gpu-jobs", "register", "--name", rid,
                     "--workdir", str(run_dir(cfg)),
                     "--note", f"{cfg['run_family']} collection batch client {len(sess)} pieces"
                               f"({k_of(cfg)} per task, seeds {seeds_of(cfg)})"]
            + pieces, cwd=ROOT, log=log)
        if rc != 0:
            return False, f"gpu-jobs register {rid} exited {rc}"
    for i, s in enumerate(mf["servers"]):
        name = srv_job_name(cfg, i)
        if name in names:
            continue
        rc, _ = pr.run_cmd(
            PYRUN + ["gpu-jobs", "register", "--name", name,
                     "--workdir", str(SERVE_LOG_DIR),
                     "--note", f"{cfg['run_family']} collection batch {cfg['model_full']} "
                               f"instance (port {s['port']}), stays up for the whole collection, killed at wrap-up",
                     "--piece",
                     f"{s['host']}:{s['gpu']}:{s['session']}:"
                     f"{SERVE_LOG_DIR / (s['session'] + '.log')}",
                     "--kind", "service", "--port", str(s["port"])],
            cwd=ROOT, log=log)
        if rc != 0:
            return False, f"gpu-jobs register {name} exited {rc}"
    if "start" not in pr.record_events().get(rid, set()):
        rc, _ = pr.run_cmd(
            PYRUN + ["record", "start", "--run-id", rid,
                     "--track", f"collect_{rid}",
                     "--cmd", f"bash {run_dir(cfg) / 'launch_clients.sh'}",
                     "--host", host, "--gpu", "cpu",
                     "--model", cfg["model_full"],
                     "--data", str(outdir_of(cfg)),
                     "--log", str(run_dir(cfg) / "logs"),
                     "--note", f"{cfg['run_family']} collection: {k_of(cfg)} trajectories per task"],
            cwd=ROOT, log=log)
        if rc != 0:
            return False, f"record start {rid} exited {rc}"
    out = outdir_of(cfg)
    out.mkdir(parents=True, exist_ok=True)
    rc, _ = pr.run_cmd(PYRUN + ["runmeta", str(out), "--cmd",
                                f"bash {run_dir(cfg) / 'launch_clients.sh'}",
                                "--kind", "collect"], cwd=ROOT, log=log)
    if rc != 0:
        return False, f"runmeta {out} exited {rc}"
    return True, ""


def step_c6_done(cfg, state, pr=None):
    """c6_done: G6 completeness -> G7 GPU memory reaching zero -> deregister from the job ledger + record finish."""
    pr = pr or Probes()
    k, n = k_of(cfg), n_units(cfg)
    want = n * k
    files = traj_files(outdir_of(cfg), cfg["env"])
    bad_tail = [f.name for f in files if not is_final(f)]
    if len(files) != want or bad_tail:
        detail = (f"G6 not complete: {outdir_of(cfg)} has {len(files)} trajectory files,"
                  f"should have {n} tasks x {k} = {want}")
        if bad_tail:
            detail += f"; also {len(bad_tail)} whose last line is not final: {bad_tail[:5]}"
        host = pr.local_host()
        alive = [s for s in client_sessions(cfg) if pr.has_session(host, s)]
        if alive:
            return waiting("collection is still running", detail + f"; {len(alive)} client sessions still alive")
        return blocked("G6 not complete and all clients are dead",
                       detail + "; not a single client session is up -- "
                       "`bash launch_clients.sh` is idempotent and supports --resume, relaunch it to fill in the missing tasks")
    capped = [f.name for f in files if (final_steps(f) or 0) >= 30]
    mf = manifest_of(cfg)
    hot = []
    for s in mf["servers"]:
        if pr.has_session(s["host"], s["session"]):
            hot.append(f"{s['session']} is still alive (tmux kill-session -t {s['session']})")
            continue
        used = pr.gpu_used_mb(s["host"], s["gpu"])
        if used is None:
            hot.append(f"{s['host']}:{s['gpu']} GPU memory cannot be probed, treating as not yet zeroed")
        elif used > FREE_MB:
            hot.append(f"{s['host']}:{s['gpu']} still holds {used} MiB")
    if hot:
        return blocked("G7 GPU memory not zeroed",
                       "collection is complete, kill all service sessions first, then re-run:\n" + head_lines(hot))
    log = step_log(cfg, "c6_done")
    names = pr.ledger_names()
    for name in [cfg["collect"]["run_id"]] + [srv_job_name(cfg, i)
                                              for i in range(len(mf["servers"]))]:
        if name not in names:
            continue
        rc, _ = pr.run_cmd(PYRUN + ["gpu-jobs", "finish", name], cwd=ROOT, log=log)
        if rc != 0:
            return blocked("job ledger deregistration failed", f"gpu-jobs finish {name} exited {rc}")
    rid = cfg["collect"]["run_id"]
    evs = pr.record_events().get(rid, set())
    if "start" in evs and "finish" not in evs:
        # The numbers (task count / trajectory count / hits on the 30-step cap) are filled in by a human, the driver only closes out the state
        rc, _ = pr.run_cmd(
            PYRUN + ["record", "finish", rid, "--status", "ok",
                     "--metric", f"trajs={len(files)}", "--metric", f"units={n}",
                     "--metric", f"steps30_hit={len(capped)}"],
            cwd=ROOT, log=log)
        if rc != 0:
            return blocked("record wrap-up failed", f"record finish {rid} exited {rc}")
    return advanced("G6/G7 passed, job ledger and record have wrapped up",
                    f"{len(files)} trajectories ({n} tasks x {k}); 30-step cap hit by {len(capped)}")


