def gate_clean_tree(pr, what):
    """G1: the working tree must be clean before launch. Returns None to mean pass, otherwise
    returns a blocked event. The HEAD stored in the record only leads back to the real code
    when the working tree is clean (the CLAUDE.md hard rule), so there is no --allow-dirty
    bypass here: the driver is an orchestrator, and committing is a human's job."""
    lines = pr.git_dirty()
    if lines is None:
        return blocked("G1 cannot probe the worktree",
                       f"git status failed, treating as a dirty tree, refusing {what};"
                       "confirm the git environment, commit first, then re-run")
    if lines:
        return blocked("G1 worktree is dirty",
                       f"{len(lines)} lines uncommitted, refusing {what} -- "
                       f"commit before launching (CLAUDE.md hard rule):\n{head_lines(lines)}")
    return None


def manifest_sha1(cfg):
    """The sha1 of the collection manifest file's bytes. Returns None if the file does not exist."""
    p = manifest_path(cfg)
    if not p.is_file():
        return None
    return hashlib.sha1(p.read_bytes()).hexdigest()


def gate_manifest_unchanged(cfg, state, what):
    """C9: which manifest an artifact was generated from must match.

    When c1_gen generates (or claims) the three launch artifacts, it records that manifest's
    sha1 into the state at that time; c2/c5, which actually execute those three things,
    recompute and compare it again. If a human changes the card number or session name in the
    manifest but forgets to regenerate with `gen-launch --force`, this blocks on the spot --
    otherwise c2 would pass G2 with the new card number but run launch_servers.py that still
    has the old card number written in it, bring vLLM up on the old card and old session, and
    then c3 would wait forever for a log that will never appear.

    Returns None to mean pass; for old state that never recorded a sha1, fill one in and then
    pass (a missing record does not count as a failure).
    """
    cur = manifest_sha1(cfg)
    if cur is None:
        return blocked("collection manifest does not exist", str(manifest_path(cfg)))
    old = state.get("manifest_sha1")
    if not old:
        state["manifest_sha1"] = cur
        return None
    if old != cur:
        return blocked(
            "manifest does not match the one used when generating the launch artifacts",
            f"{manifest_path(cfg)} was modified after c1_gen generated the three launch artifacts"
            f"(recorded sha1 {old[:12]}, now {cur[:12]}); under {run_dir(cfg)}"
            f"the card number, session name, and port in launch_servers.py / launch_clients.sh"
            f"are still the old ones, running {what} directly would target the wrong card. Regenerate first:\n"
            f"  python3 run.py gen-launch --config {manifest_path(cfg)} --force\n"
            "before regenerating, also double-check whether servers[].gpu is really free, and whether the session name"
            "was updated accordingly; after generating, delete manifest_sha1 in the state file logs/pipeline/"
            f"{cfg['run_family']}/state.json (or set it to the new value)"
            "then re-run, only then will the driver recognize this new one")
    return None


def smoke_traj_check(d, k, seeds, env):
    """G4's criterion: K files, each with a final last line, each meta's seed matching the seed
    table position by position. Returns (ok, text explaining which one failed)."""
    if seeds and len(seeds) < k:
        # If the seed table is shorter than K: report the criterion as failed directly, do not let
        # seeds[i] raise IndexError and turn a ready-made blocked into a traceback (review C10)
        return False, (f"the seed table has only {len(seeds)} entries ({seeds}), at {k} per task"
                       f"it needs {k}, cannot align position by position")
    files = traj_files(d, env)
    if len(files) != k:
        return False, (f"{d} has {len(files)} trajectory files, at {k} per task it should be "
                       f"{k}: {[f.name for f in files]}")
    probs = []
    for i in range(k):
        if k > 1:
            hit = [f for f in files if f.stem.endswith(f"_r{i}")]
            if len(hit) != 1:
                probs.append(f"trajectory {i} (filename ending in _r{i}) found {len(hit)}")
                continue
            f = hit[0]
        else:
            f = files[0]
        if not is_final(f):
            probs.append(f"{f.name} last line is not type=final")
        if seeds:
            got = meta_seed(f)
            if got != seeds[i]:
                probs.append(f"{f.name}'s gen_settings.seed={got},"
                             f"seed table position {i} is {seeds[i]}")
    return (not probs), "\n".join(probs)


