# ---------------------------------------------------------------- probing and external actions

def ssh_argv(host, cmd):
    """Local runs go through bash -c, remote through ssh. BatchMode fails immediately when
    passwordless login is not set up, instead of hanging at a password prompt; ConnectTimeout
    returns within 10 seconds when the machine is unreachable."""
    if host == local_host():
        return ["bash", "-c", cmd]
    return ["ssh", "-n", *SSH_OPTS, host, cmd]


def has_session(host, sess):
    """Whether a tmux session named sess exists on host. When the probe cannot run (ssh fails),
    report it as "does not exist"; the caller decides case by case whether that counts as a gate
    failure -- c2/c5 use it to decide whether to launch, c6 uses it to distinguish "still
    running" from "all dead"; neither place will mistake an unreachable probe for completion."""
    argv = ssh_argv(host, f"tmux has-session -t {shlex.quote(sess)}")
    return subprocess.run(argv, capture_output=True, text=True).returncode == 0


def gpu_used_mb(host, gpus):
    """G7: how much GPU memory (MiB) is still held on the target card. Returns int; returns None
    when the probe cannot run -- fail-closed, and the caller treats it as "not zeroed"."""
    cmd = (f"nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits "
           f"-i {shlex.quote(str(gpus))}")
    r = subprocess.run(ssh_argv(host, cmd), capture_output=True, text=True)
    if r.returncode != 0:
        return None
    tot = 0
    for line in r.stdout.split("\n"):
        line = line.strip()
        if not line:
            continue
        try:
            tot += int(line)
        except ValueError:
            return None
    return tot


def http_get(url, timeout=10):
    """G3's second criterion. Returns (ok, body or reason). Uses curl instead of urllib:
    the runbook and MANIFEST.md both document this same curl command, so the two stay in sync."""
    r = subprocess.run(["curl", "-s", "-m", str(timeout), url],
                       capture_output=True, text=True)
    if r.returncode != 0:
        return False, f"curl rc={r.returncode} {(r.stderr or '').strip()[:120]}"
    if not r.stdout.strip():
        return False, "empty response"
    return True, r.stdout.strip()[:200]


def run_cmd(argv, cwd=None, log=None, env=None):
    """Run a subcommand. Output goes to both stdout and the per-step log; returns (rc, output text)."""
    argv = [str(a) for a in argv]
    line = shlex.join(argv)
    print("  $ " + line, flush=True)
    r = subprocess.run(argv, cwd=str(cwd or ROOT), capture_output=True,
                       text=True, env=env)
    out = (r.stdout or "") + (r.stderr or "")
    if log:
        Path(log).parent.mkdir(parents=True, exist_ok=True)
        with open(log, "a") as f:
            f.write(f"# [{time.strftime('%F %T')}] {line}\n{out}"
                    f"# rc={r.returncode}\n")
    if out.strip():
        print(out.rstrip("\n"), flush=True)
    return r.returncode, out


def boundary_counts(cfg):
    """Raw material for a1_stats: the untruncated cut count for each event. Following the
    precedent in accept_v3diff.py:21-22, push pipeline/annotate onto sys.path and import it,
    rather than duplicating the cut logic."""
    d = str(ROOT / "pipeline" / "annotate")
    if d not in sys.path:
        sys.path.insert(0, d)
    from build import collect_events            # noqa: PLC0415
    from rules import boundaries                # noqa: PLC0415
    events = collect_events([Path(r) for r in cfg["traj_runs"]], cfg["env"])
    events = [e for e in events if e["model"] == cfg["model_full"]]
    # max_bounds set to 10**9 = no truncation: the stats need "how many cuts there originally
    # were", to answer "how many did the cap of 64 cut off"
    return [len(boundaries(e["think"], max_bounds=10 ** 9)) for e in events]


def ledger_names():
    """Job names in the job ledger's active list (read-only; writes to the job ledger always go through the CLI)."""
    p = ROOT / "ops" / "jobs.json"
    if not p.exists():
        return set()
    try:
        reg = json.loads(p.read_text())
    except Exception:
        return set()
    return {j.get("name") for j in reg.get("active", [])}


def record_events():
    """Which events have been recorded for each run_id in runs.jsonl ({run_id: {"start", "finish"}})."""
    p = ROOT / "ops" / "runs.jsonl"
    out = {}
    if not p.exists():
        return out
    for line in p.read_text().split("\n"):
        line = line.strip()
        if not line:
            continue
        try:
            ev = json.loads(line)
        except Exception:
            continue
        rid = ev.get("run_id")
        if rid:
            out.setdefault(rid, set()).add(ev.get("ev"))
    return out


