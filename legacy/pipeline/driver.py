def mark_launched(state, key, what=""):
    """Only recorded once the driver actually calls the launcher (after rc=0)."""
    if not isinstance(state.get("launched"), dict):
        state["launched"] = {}
    state["launched"][key] = {"t": time.strftime("%F %T"), "what": what}
    return state["launched"][key]


def already_launched(what, key, mark, extra=""):
    """The criterion is not met but this batch's marker is present: do not relaunch, wait as is (return 0).

    Never report launched/return 3 here -- for a session already running, the launcher just
    prints SKIP and still returns 0, so treating rc as "launched this time" would write a false
    launch record; and for a slot that has already finished, its session is long gone, so a
    blind launch would append it a false RUNMETA and stuff run_id back into the job ledger's
    active list (review C2/C7).
    """
    return waiting(f"{what} was already launched earlier, not relaunching this time",
                   f"mark {key} records launch time {mark.get('t')}"
                   + (f"({mark.get('what')})" if mark.get("what") else "")
                   + "; the criteria are not yet met, it may still be running or may have died partway. Check where it stands:\n"
                     "  python3 run.py gpu-jobs\n"
                     "  python3 run.py gpu-jobs watch\n"
                   + (extra + "\n" if extra else "")
                   + f"after confirming that batch is neither running nor finished (e.g. it crashed), delete "
                     f"{key!r} under launched in the state file and re-run, only then will the driver relaunch")


