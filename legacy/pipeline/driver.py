def step_a3_gates(cfg, state, pr=None):
    """a3_gates: G9 task-list line count + G11 spot-check files laid out + byte-for-byte rebuild comparison."""
    pr = pr or Probes()
    lists = split_lists(cfg)
    if not lists:
        return blocked("G9 has no task list to check", "config missing official_split_files")
    probs, counts = [], {}
    seen = {}
    for name, ids in lists.items():
        counts[name] = len(ids)
        if not ids:
            probs.append(f"{name} task list is empty")
        if len(set(ids)) != len(ids):
            probs.append(f"{name} task list has duplicate task_id")
        for u in ids:
            if u in seen and seen[u] != name:
                probs.append(f"task_id {u} is in both {seen[u]} and {name} piles")
            seen[u] = name
    if probs:
        return blocked("G9 task list check failed", "\n".join(probs[:10]))
    out = data_out(cfg)
    for n in ("qa_sample.txt", CHECK_FILE):
        if not (out / n).is_file():
            return blocked("G11 spot-check file does not exist", f"{out / n} does not exist")
    ref = out.parent / f"{out.name}_rebuild_ref"
    if ref.exists():
        return blocked("the backup from the last rebuild comparison is still there",
                       f"{ref} is the original-output backup left from the last byte-by-byte rebuild comparison -- "
                       "check it against the current output by hand before deleting it and redoing the rebuild")
    rebuild = list(BUILD_FILES) + list(PARAM_FILES)
    ref.mkdir(parents=True)
    for rel in rebuild:
        dst = ref / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(out / rel, dst)
    log = step_log(cfg, "a3_gates")
    for task in ("ann-build", "ann-params"):
        rc, _ = pr.run_cmd(PYRUN + [task, "--config", cfg["_path"]],
                           cwd=ROOT, log=log)
        if rc != 0:
            return blocked("rebuild run failed",
                           f"{task} returned {rc}; the original-output backup is at {ref},"
                           "check by hand and decide whether to copy it back")
    diff = [rel for rel in rebuild
            if not filecmp.cmp(ref / rel, out / rel, shallow=False)]
    if diff:
        return blocked("byte-by-byte rebuild comparison mismatch",
                       f"{len(diff)} files differ between the two rebuilds: {diff};"
                       f"the first output's backup is at {ref} (do not delete it yet, it is evidence)")
    shutil.rmtree(ref)
    return advanced("G9/G11/byte-by-byte rebuild all passed",
                    f"task list {counts};{len(rebuild)} files identical byte-for-byte between the two rebuilds")


