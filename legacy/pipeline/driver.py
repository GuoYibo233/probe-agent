def train_log_records(run_out):
    p = Path(run_out) / "train_log.jsonl"
    if not p.is_file():
        return []
    recs = []
    for line in p.read_text().split("\n"):
        line = line.strip()
        if not line:
            continue
        try:
            recs.append(json.loads(line))
        except Exception:
            continue
    return recs


def smoke_train_check(run_out, cell):
    """The machine-checkable half of G14: smoke really finished + ctool's ALIGN_CHECK PASS.

    Criterion = train_log.jsonl has event=start and event=done, and best/ exists; ctool also
    requires ALIGN_CHECK.json's PASS. Missing done or missing best/ always fails -- "finished
    running" is not something to leave ambiguous.

    "loss is decreasing" is only judged when there are two or more event=step records: the
    three training scripts write a step record only every 50 optimization steps
    (train_causal_tool.py:422's `if gstep % 50 == 0`), while --smoke pins the training amount
    at 6-16 optimization steps, so a smoke run that completes usually has zero step records
    (observed in logs/new1_p1b17_gptoss_ctool_smoke_gc_t108g0.log: [[EXITCODE:0]] +
    event=done, 0 event=step records). When there are fewer than two records, this does not
    block; it just records "loss sequence too short, not judged" into this step's history
    detail (review C6).

    Returns (ok, reason for failure, a note worth recording even when it passes).

    TODO (execution-block hardening): "decreasing" currently only compares the first and last
    loss records; whether a real run should look at slope, and whether to also verify the
    checkpoint can be loaded back (G15), will be decided once the first batch's actual
    train_log comes in.
    """
    p = Path(run_out)
    if not (p / "train_log.jsonl").is_file():
        return False, f"{p}/train_log.jsonl does not exist (smoke has not run, or this is not the right output dir)", ""
    recs = train_log_records(p)
    if not any(r.get("event") == "start" for r in recs):
        return False, f"{p}/train_log.jsonl has no event=start record", ""
    if not any(r.get("event") == "done" for r in recs):
        n_eval = sum(1 for r in recs if r.get("event") == "eval")
        return False, (f"{p}/train_log.jsonl has no event=done"
                       f"(smoke has not finished; {n_eval} eval records so far)"), ""
    if not (p / "best").is_dir():
        return False, f"{p}/best does not exist (smoke finished but did not save the best checkpoint)", ""
    note = ""
    losses = [r["loss"] for r in recs
              if r.get("event") == "step" and isinstance(r.get("loss"), (int, float))]
    if len(losses) >= 2:
        if losses[-1] >= losses[0]:
            return False, f"{p}'s loss did not drop: first {losses[0]} last {losses[-1]}", ""
    else:
        note = (f"{p}: train_log.jsonl has only {len(losses)} event=step records,"
                "the loss sequence is too short to judge whether this cell's loss dropped (smoke writes one every 50 optimizer steps,"
                "it doesn't run that many)")
    if cell == "ctool":
        a = p / "ALIGN_CHECK.json"
        if not a.is_file():
            return False, f"{p}/ALIGN_CHECK.json does not exist (G13 alignment check has not run)", ""
        try:
            rep = json.loads(a.read_text())
        except Exception as e:
            return False, f"cannot read {a}: {type(e).__name__}: {e}", ""
        if not rep.get("PASS"):
            return False, (f"{a}'s PASS={rep.get('PASS')}"
                           f"(hidden maxdiff {rep.get('maxdiff_hidden')})"), ""
    return True, "", note


def full_train_check(run_out):
    """t2's completion criterion: best/ exists + train_log reaches event=done.
    TODO (execution-block hardening): "3 epochs completed" currently just trusts the done
    record the training script writes itself; a real epoch-by-epoch check needs the eval
    record count convention pinned down first, to be settled once the first full run finishes."""
    p = Path(run_out)
    if not (p / "best").is_dir():
        return False, f"{p}/best does not exist"
    recs = train_log_records(p)
    if not any(r.get("event") == "done" for r in recs):
        n_eval = sum(1 for r in recs if r.get("event") == "eval")
        return False, f"{p}/train_log.jsonl has no event=done ({n_eval} epochs finished so far)"
    return True, ""


def theta_all_null(ctool_run):
    """If neither risk tier has a resolution -> record this batch's call tier as N/A (the
    convention in gates.md Sec. 3.4). If the report cannot be read, treat it as "not N/A" --
    do not let a file read failure pass itself off as a legitimately missing cell."""
    p = Path(ctool_run) / "REPLAY_REPORT.json"
    if not p.is_file():
        return False
    try:
        rep = json.loads(p.read_text())
    except Exception:
        return False
    ch = rep.get("chosen_theta")
    if not isinstance(ch, dict) or not ch:
        return False
    return all(v is None for v in ch.values())


