def load_cfg(path):
    p = Path(path)
    if not p.is_absolute():
        p = ROOT / p
    if not p.exists():
        raise SystemExit(f"batch config does not exist: {p}")
    try:
        cfg = json.loads(p.read_text())
    except Exception as e:
        raise SystemExit(f"cannot read batch config {p}: {type(e).__name__}: {e}")
    for k in ("run_family", "env", "model_short", "model_full", "data_out",
              "traj_runs", "collect"):
        if k not in cfg:
            raise SystemExit(f"batch config missing field {k}: {p}")
    for k in ("manifest", "run_id"):
        if k not in cfg["collect"]:
            raise SystemExit(f"batch config's collect section missing field {k}: {p}")
    cfg["_path"] = str(p)
    return cfg


