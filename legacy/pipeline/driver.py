# ---------------------------------------------------------------- small utilities

def file_contains(path, needle, block=1 << 20):
    """Find a line in a large log. Read it streamed in chunks; do not load a several-hundred-MB vLLM log entirely into memory."""
    p = Path(path)
    if not p.exists():
        return False
    nb = needle.encode()
    tail = b""
    with open(p, "rb") as f:
        while True:
            buf = f.read(block)
            if not buf:
                return False
            if nb in tail + buf:
                return True
            # Keep len(needle)-1 bytes to join with the next chunk, so a line crossing a chunk boundary is not missed
            tail = buf[-(len(nb) - 1):] if len(nb) > 1 else b""


def traj_files(d, env):
    return sorted(Path(d).glob(f"{env}_*.jsonl")) if Path(d).is_dir() else []


def _first_last(path, tail_bytes=65536):
    """The trajectory file's first line (meta) and last line (final). Reads only the first line
    plus the last 64KB -- G6 needs to glance at each of 1260 files on NFS, and reading the whole
    file in is too expensive; in the final record, eval is already truncated to 600 characters,
    so one record is nowhere near 64KB."""
    p = Path(path)
    if not p.is_file():
        return None, None
    with open(p, "rb") as f:
        first = f.readline()
        f.seek(0, 2)
        size = f.tell()
        f.seek(max(0, size - tail_bytes))
        tail = f.read()
    lines = [ln for ln in tail.decode("utf-8", "replace").split("\n") if ln.strip()]
    if not lines:
        return None, None
    return first.decode("utf-8", "replace").strip() or None, lines[-1]


def is_final(path):
    """Whether the last line is type=final (the per-file criterion for G4/G6)."""
    _, last = _first_last(path)
    if last is None:
        return False
    try:
        return json.loads(last).get("type") == "final"
    except Exception:
        return False


def meta_seed(path):
    """The seed this trajectory used, from the trajectory's meta (gen_settings.seed); returns None if it cannot be read."""
    first, _ = _first_last(path)
    if first is None:
        return None
    try:
        return (json.loads(first).get("gen_settings") or {}).get("seed")
    except Exception:
        return None


def final_steps(path):
    """The steps field in the last line's final record (needed for counting tasks that hit the 30-step cap); returns None if it cannot be read."""
    _, last = _first_last(path)
    if last is None:
        return None
    try:
        rec = json.loads(last)
        return rec.get("steps") if rec.get("type") == "final" else None
    except Exception:
        return None


def pct(sorted_vals, q):
    """Index-based percentile: take the element at index floor(q*n) (0-indexed), no interpolation, for easy reconciliation.

    The definition must match q() in the pipeline/annotate/build.py:468 report verbatim -- the
    p50/p90/p99 that a1_stats prints into the state file are what a human uses to decide
    max_bounds, and after a2, build.py writes the same-named numbers into the ANNOTATE_REPORT
    archive; the two definitions disagree by one slot exactly when q*n is an integer
    (2026-08-22 review C4). This follows build's index-based version, so one batch of data has
    only one definition.
    """
    n = len(sorted_vals)
    return sorted_vals[min(n - 1, max(0, int(q * n)))]


def dist_of(counts):
    s = sorted(counts)
    return dict(n_events=len(s), min=s[0], p50=pct(s, 0.5), p90=pct(s, 0.9),
                p99=pct(s, 0.99), max=s[-1],
                over_32=sum(1 for x in s if x > 32),
                over_64=sum(1 for x in s if x > 64),
                over_128=sum(1 for x in s if x > 128),
                over_256=sum(1 for x in s if x > 256))


def client_sessions(cfg):
    """The tmux session name launch_clients.sh will start. The naming scheme follows gen_launch.py's
    `tm "{prefix}_$1_s$7"`; prefix defaults to the first two segments of run_id joined together."""
    mf = manifest_of(cfg)
    prefix = mf.get("client_session_prefix")
    if not prefix:
        parts = mf["run_id"].split("_")
        tail = "".join(parts[:2]) if len(parts) >= 2 else mf["run_id"]
        prefix = f"new1_{tail}"
    out = []
    for c in mf["clients"]:
        for sid in range(c["num_shards"]):
            out.append(f"{prefix}_{c['tag']}_s{sid}")
    return out


