# ---------------------------------------------------------------- events and state

def _ev(status, event, detail="", decision=None, advance=False):
    return dict(status=status, event=event, detail=detail,
                decision_needed=decision, advance=advance)


def advanced(event, detail=""):
    """This step is done; move the pointer forward one slot."""
    return _ev("ready", event, detail, advance=True), 0


def launched(event, detail="", advance=True):
    """A GPU job was launched this time; run again once it finishes."""
    return _ev("launched", event, detail, advance=advance), 3


def blocked(event, detail):
    """The gate did not pass. The reason lands in the state file and stderr; the pointer does not move."""
    return _ev("blocked", event, detail), 1


def waiting(event, detail):
    """The job launched by the previous step is still running -- neither failed nor done: leave it as is and wait for the next run."""
    return _ev("ready", event, detail), 0


def decide(event, detail, question):
    """Stop point: something needs a human ruling; write the decision into the batch config and run again."""
    return _ev("awaiting_decision", event, detail, decision=question), 4


def ident_of(cfg):
    ident = {k: cfg.get(k) for k in IDENT_KEYS}
    ident["collect_run_id"] = cfg["collect"]["run_id"]
    blob = json.dumps(ident, sort_keys=True, ensure_ascii=False)
    return hashlib.sha1(blob.encode()).hexdigest()[:12]


def fresh_state(cfg):
    return dict(config=cfg["_path"], run_family=cfg["run_family"],
                ident=ident_of(cfg), stage=STEPS[0]["stage"],
                step=STEPS[0]["name"], status="ready", reason=None,
                decision_needed=None, launched={}, history=[])


def state_path(cfg):
    return LOG_ROOT / cfg["run_family"] / "state.json"


def load_state(cfg):
    """Read the state. If it cannot be read / keys are missing / the step name is unrecognized /
    the batch identity does not match, refuse to write on top of it in every case -- following
    the params consistency precedent in run.py run_recipe: better to have a human take a look
    than to let it overwrite another run's state."""
    p = state_path(cfg)
    if not p.exists():
        return fresh_state(cfg)
    try:
        st = json.loads(p.read_text())
    except Exception as e:
        raise SystemExit(f"cannot read state file {p}: {type(e).__name__}: {e};"
                         "manually confirm its origin, delete it, then re-run (the driver won't overwrite state it can't understand)")
    if not isinstance(st, dict):
        raise SystemExit(f"state file is not an object: {p}; manually confirm, then delete it and re-run")
    miss = [k for k in ("run_family", "ident", "step", "status") if k not in st]
    if miss:
        raise SystemExit(f"state file missing field {miss}: {p}; manually confirm, then delete it and re-run")
    if st["step"] != "done" and st["step"] not in STEP_NAMES:
        raise SystemExit(f"unrecognized step name in the state file: {st['step']}({p});"
                         "manually confirm, then delete it and re-run")
    if st["ident"] != ident_of(cfg) or st["run_family"] != cfg["run_family"]:
        raise SystemExit(
            f"{p} records a run for a different set of batch parameters (ident={st['ident']},"
            f"this run's ident={ident_of(cfg)}), refusing to overwrite;"
            f"use a different run_family, or align the config back to the original set")
    st.setdefault("history", [])
    st.setdefault("reason", None)
    st.setdefault("decision_needed", None)
    # The launch marker travels with the state file (old state without this key -> fill in an empty one, treat old bookkeeping as not launched)
    if not isinstance(st.get("launched"), dict):
        st["launched"] = {}
    st["config"] = cfg["_path"]
    return st


def save_state(cfg, st):
    """Atomic write: tmp + os.replace, following run.py save_state."""
    d = state_path(cfg).parent
    d.mkdir(parents=True, exist_ok=True)
    tmp = d / "state.json.tmp"
    tmp.write_text(json.dumps(st, ensure_ascii=False, indent=1))
    os.replace(tmp, d / "state.json")


def apply_event(st, step, event):
    """Write the result of one advance into the state: state fields + one history entry. Only
    advance moves the pointer; moving it to the end means done."""
    st["status"] = event["status"]
    st["reason"] = event["detail"] or None
    st["decision_needed"] = event["decision_needed"]
    st["history"].append(dict(t=time.strftime("%F %T"), step=step["name"],
                              event=event["event"], detail=event["detail"]))
    if event["advance"]:
        i = STEP_NAMES.index(step["name"])
        if i + 1 < len(STEPS):
            st["step"] = STEPS[i + 1]["name"]
            st["stage"] = STEPS[i + 1]["stage"]
        else:
            st["step"] = "done"
            st["status"] = "done"
    return st


