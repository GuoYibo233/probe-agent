#!/usr/bin/env python3
"""Pipeline driver (build design doc Sec. 7): one command, resumable, advancing at most one
step per invocation.

It is an orchestrator, not new experiment code -- every step of collect / annotate / train /
eval hands off to an existing entry point (`run.py <task>` / `run.py recipe` /
`launch_servers.py` / `launch_clients.sh` / `launch-probe` / `launch-eval`); it only does three
things itself: decide which step can advance right now, check the gates (G1-G22) on the spot,
and write the result to the state file.

Usage:
  python3 run.py pipeline --config pipeline/configs/np821_gptoss.json
  python3 run.py pipeline --config <same config> --status   # read-only print, no advance

State file: logs/pipeline/<run_family>/state.json (logs/ is in .gitignore, so state changes
do not dirty the working tree). Per-step logs sit in the same directory as <step>.log; the
subprocess's stdout/stderr all go there.

Exit codes (design doc Sec. 7):
  0  advanced one step / everything is done / the previous step's job has not finished yet
     (leave it as is and run again next time)
  3  a GPU job was launched this time (run again once it finishes)
  4  awaiting_decision: something needs a human ruling; write the decision into the batch
     config and run again
  1  gate failed (the reason lands in both the state file and stderr)

Launch registration (fix from the 2026-08-22 review C2/C7): only when t2_full / e1_tool /
e2_call actually call the launcher does the state file record a marker in `launched`. On a
second invocation for the same batch, if the criterion is not met but the marker is present,
the driver does not relaunch; it returns 0 and tells the human to check
`python3 run.py gpu-jobs` -- from now on, exit code 3 means only "this time it was really
launched"; there is no more false bookkeeping of "already launched but reporting launched
again".

Step table (appworld batch instantiation, one advance function per step; the transition table
is STEPS below):
  collect   c1_gen c2_servers c3_health c4_smoke c5_clients c6_done
  annotate  a1_stats a2_build a3_gates
  train     t1_smoke t2_full t3_close
  eval      e1_tool e2_call m1_matrix

Three implementation disciplines (design doc Sec. 7, end):
  - All probing and external actions live in `Probes`; swap in fake functions in a unit test
    and the whole state machine runs dry;
  - A criterion would rather block than pass -- the steps after t1 really run in the execution
    block; the code has TODOs marking what still needs hardening, but nowhere does "could not
    check" count as passing;
  - Every ssh probe carries `-o BatchMode=yes -o ConnectTimeout=10` (the gpu_jobs precedent;
    launch_common.has_session does not carry these two flags, do not copy it).
"""

