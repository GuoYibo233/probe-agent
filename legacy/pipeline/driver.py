# ---------------------------------------------------------------- entry point

def print_status(cfg, st):
    print(f"pipeline {st['run_family']}  config {st.get('config')}")
    print(f"  current: {st.get('stage')} / {st['step']}  status {st['status']}")
    if st.get("reason"):
        print("  reason: " + str(st["reason"]).replace("\n", "\n        "))
    if st.get("decision_needed"):
        print(f"  awaiting ruling: {st['decision_needed']}")
    if st.get("cutpoint_stats"):
        print("  cut-point distribution: " + json.dumps(st["cutpoint_stats"], ensure_ascii=False))
    if st.get("launched"):
        # A human should be able to see which batch and which step have already been launched, and when
        print("  launch marker: " + ", ".join(
            f"{k}@{v.get('t')}" for k, v in sorted(st["launched"].items())))
    done = st["step"] == "done"
    idx = len(STEPS) if done else STEP_NAMES.index(st["step"])
    for i, s in enumerate(STEPS):
        mark = "x" if i < idx else (">" if i == idx else " ")
        print(f"  [{mark}] {s['name']:<12} {s['desc']}")
    for h in st.get("history", [])[-5:]:
        print(f"  {h['t']}  {h['step']:<12} {h['event']}")
    print(f"  state file: {state_path(cfg)}")
    return 0


def main(argv):
    cfg_path, only_status = None, False
    it = iter(argv)
    for a in it:
        if a == "--config":
            cfg_path = next(it, None)
            if cfg_path is None:
                raise SystemExit("--config must be followed by a batch config json")
        elif a == "--status":
            only_status = True
        elif a in ("-h", "--help"):
            print(__doc__)
            return 0
        else:
            raise SystemExit(f"unrecognized argument: {a} (only --config / --status are recognized)")
    if not cfg_path:
        raise SystemExit("--config <batch config json> is required (see run.py show pipeline for usage)")
    cfg = load_cfg(cfg_path)
    st = load_state(cfg)
    if only_status:
        return print_status(cfg, st)
    if st["step"] == "done":
        print(f"pipeline {cfg['run_family']} is fully complete. State: {state_path(cfg)}")
        return 0
    step = step_by_name(st["step"])
    print(f"[{step['name']}] {step['desc']}")
    event, code = step["fn"](cfg, st)
    apply_event(st, step, event)
    save_state(cfg, st)
    print(f"-> {event['status']}: {event['event']}")
    if event["detail"]:
        out = sys.stderr if code == 1 else sys.stdout
        print(event["detail"], file=out)
    if event["decision_needed"]:
        print(f"awaiting ruling: {event['decision_needed']}")
    nxt = "done" if st["step"] == "done" else st["step"]
    print(f"next step: {nxt}   state: {state_path(cfg)}   exit code {code}")
    return code


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
